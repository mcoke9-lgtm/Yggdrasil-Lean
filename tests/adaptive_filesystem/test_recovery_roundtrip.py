"""Synthetic AF recovery contract; not the production Adaptive Filesystem runtime.

Model mapping:
- Initial wave: TERA=system under test, FIRA=fixture, WATA=runner, AIRA=assertions.
- Particle report: generated by AIRA-of-TERA from TERA root state and leaf-like parts.
- The particle report generates the second FIRA-associated wave.
- next_steps_intended is a peer container, not a sixth scalar checkpoint field.
"""
from copy import deepcopy
import unittest

REQUIRED_PEER_CONTAINERS = ("TERA", "FIRA", "WATA", "AIRA", "next_steps_intended")


def intended_container():
    return {
        "intended_steps": [{"step_id": "S1", "action": "review_round_trip", "status": "planned"}],
        "intended_changes": [{"change_id": "C1", "operation": "revise_label", "status": "planned"}],
        "post_connection_report": {"required": True, "retention": "retain_with_provenance"},
        "evidence_refs": ["fixture-001"],
        "status": "planned",
        "dependencies": [],
        "verification_needs": ["round_trip_preservation"],
    }


def wave_exists(records, relationships, next_steps=None):
    containers = {
        "TERA": {"records": deepcopy(records), "relationships": deepcopy(relationships)},
        "FIRA": {"role": "fixture"},
        "WATA": {"role": "runner"},
        "AIRA": {"role": "assertions"},
        "next_steps_intended": deepcopy(next_steps if next_steps is not None else intended_container()),
    }
    return {"form": "wave", "association": "initial", "containers": containers}


def validate_peer_containers(wave):
    if not isinstance(wave, dict) or wave.get("form") != "wave":
        return {"status": "INVALID_INPUT", "reasons": ["wave_shape_invalid"]}
    containers = wave.get("containers")
    if not isinstance(containers, dict):
        return {"status": "INVALID_INPUT", "reasons": ["peer_container_map_missing"]}
    missing = [name for name in REQUIRED_PEER_CONTAINERS if name not in containers]
    if missing:
        return {"status": "INVALID", "reasons": ["peer_container_missing:" + name for name in missing]}
    if not isinstance(containers["next_steps_intended"], dict):
        return {"status": "INVALID", "reasons": ["next_steps_intended_not_container"]}
    required_members = ("intended_steps", "intended_changes", "post_connection_report",
                        "evidence_refs", "status", "dependencies", "verification_needs")
    absent = [name for name in required_members if name not in containers["next_steps_intended"]]
    if absent:
        return {"status": "INVALID", "reasons": ["next_steps_member_missing:" + name for name in absent]}
    return {"status": "VALID", "reasons": []}


def validate_wave(wave):
    peer_check = validate_peer_containers(wave)
    if peer_check["status"] != "VALID":
        return peer_check
    tera = wave["containers"]["TERA"]
    records, relationships = tera.get("records"), tera.get("relationships")
    if not isinstance(records, list) or not isinstance(relationships, list):
        return {"status": "INVALID_INPUT", "reasons": ["collections_invalid"]}
    record_ids = [r.get("record_id") for r in records if isinstance(r, dict)]
    rel_ids = [r.get("relationship_id") for r in relationships if isinstance(r, dict)]
    if len(record_ids) != len(records) or any(not x for x in record_ids):
        return {"status": "INVALID_INPUT", "reasons": ["record_identity_invalid"]}
    if len(rel_ids) != len(relationships) or any(not x for x in rel_ids):
        return {"status": "INVALID_INPUT", "reasons": ["relationship_identity_invalid"]}
    if len(set(record_ids)) != len(record_ids):
        return {"status": "INVALID", "reasons": ["duplicate_record"]}
    if len(set(rel_ids)) != len(rel_ids):
        return {"status": "INVALID", "reasons": ["duplicate_relationship"]}
    by_id = set(record_ids)
    for rel in relationships:
        if rel.get("source_id") not in by_id or rel.get("target_id") not in by_id:
            return {"status": "INVALID", "reasons": ["endpoint_missing"]}
        if not rel.get("provenance"):
            return {"status": "INVALID", "reasons": ["provenance_missing"]}
        if not rel.get("relationship_type") or not rel.get("status"):
            return {"status": "INVALID", "reasons": ["relationship_semantics_missing"]}
    return {"status": "VALID", "reasons": []}


def collapse(wave):
    """Compose particle state without applying planned changes."""
    return {"form": "particle", "tera_state": deepcopy(wave["containers"]["TERA"]),
            "next_steps_intended": deepcopy(wave["containers"]["next_steps_intended"])}


def assertions_aira(source_wave, reconstructed_wave):
    """Initial-wave AIRA assertions validate; they do not generate reports."""
    source_check, result_check = validate_wave(source_wave), validate_wave(reconstructed_wave)
    if source_check["status"] == "UNKNOWN" or result_check["status"] == "UNKNOWN":
        return {"status": "UNKNOWN", "reasons": ["source_or_result_unavailable"]}
    if source_check["status"] != "VALID" or result_check["status"] != "VALID":
        return {"status": "FAIL", "reasons": source_check["reasons"] + result_check["reasons"]}
    differences = [key for key in ("containers",) if source_wave.get(key) != reconstructed_wave.get(key)]
    return {"status": "FAIL" if differences else "PASS",
            "reasons": ["round_trip_difference:" + key for key in differences]}


def aira_of_tera_report(particle):
    """Particle-form report from TERA root state and its leaf-like parts."""
    tera_state = particle.get("tera_state", {})
    records, relationships = tera_state.get("records", []), tera_state.get("relationships", [])
    leaf_parts = [
        {"record_id": r.get("record_id"), "provenance": r.get("provenance"), "role": r.get("role")}
        for r in records if isinstance(r, dict) and r.get("role") == "leaf"
    ]
    return {
        "generated_by": "AIRA-of-TERA",
        "form": "particle_report",
        "tera_state": deepcopy(tera_state),
        "leaf_parts": leaf_parts,
        "relationship_evidence": [
            {"relationship_id": r.get("relationship_id"), "status": r.get("status"),
             "provenance": r.get("provenance")}
            for r in relationships if isinstance(r, dict)
        ],
        "next_steps_intended": deepcopy(particle.get("next_steps_intended")),
    }


def activate(report):
    """Generate second FIRA-associated wave from particle report."""
    return {"form": "wave", "association": "second_fira", "report": deepcopy(report)}


def generate_post_connection_report(attempt):
    """Generate a report for success, partial, blocked, failure, or unknown outcomes."""
    outcome = attempt.get("outcome", "UNKNOWN")
    if outcome not in ("SUCCESS", "PARTIAL", "BLOCKED", "FAILED", "UNKNOWN"):
        outcome = "UNKNOWN"
    return {
        "report_type": "post_connection",
        "generated": True,
        "target": attempt.get("target", "UNKNOWN"),
        "source_id": attempt.get("source_id", "UNKNOWN"),
        "source_version": attempt.get("source_version", "UNKNOWN"),
        "outcome": outcome,
        "evidence_observed": deepcopy(attempt.get("evidence_observed", [])),
        "validation": deepcopy(attempt.get("validation", {"status": "UNKNOWN"})),
        "recovered_relationships": deepcopy(attempt.get("recovered_relationships", [])),
        "losses_ambiguities_contradictions": deepcopy(attempt.get("issues", [])),
        "intended_changes": deepcopy(attempt.get("intended_changes", [])),
        "actual_changes": deepcopy(attempt.get("actual_changes", [])),
        "unverified_boundaries": deepcopy(attempt.get("unverified_boundaries", ["connection_runtime_unverified"])),
        "next_justified_action": attempt.get("next_action", "review_evidence"),
        "persistence_status": "NOT_VERIFIED",
    }


def fixture():
    records = [
        {"record_id": "A", "provenance": "fixture-001", "role": "root"},
        {"record_id": "B", "provenance": "fixture-001", "role": "leaf"},
    ]
    relationships = [{
        "relationship_id": "R1", "source_id": "A", "target_id": "B",
        "relationship_type": "contains", "direction": "A_to_B",
        "provenance": "fixture-001", "status": "unresolved",
    }]
    return wave_exists(records, relationships)


class RecoveryRoundTripTests(unittest.TestCase):
    def setUp(self):
        self.source = fixture()
        self.particle = collapse(self.source)
        self.report = aira_of_tera_report(self.particle)
        self.second_wave = activate(self.report)

    def test_01_baseline_round_trip_preserves_all_peer_containers(self):
        reconstructed = deepcopy(self.source)
        self.assertEqual(assertions_aira(self.source, reconstructed)["status"], "PASS")
        self.assertEqual(set(reconstructed["containers"]), set(REQUIRED_PEER_CONTAINERS))

    def test_02_missing_peer_container_fails_even_when_other_fields_are_valid(self):
        damaged = deepcopy(self.source)
        del damaged["containers"]["next_steps_intended"]
        result = validate_wave(damaged)
        self.assertEqual(result["status"], "INVALID")
        self.assertIn("peer_container_missing:next_steps_intended", result["reasons"])

    def test_03_sixth_component_must_be_an_object_with_its_own_shape(self):
        damaged = deepcopy(self.source)
        damaged["containers"]["next_steps_intended"] = "review later"
        self.assertIn("next_steps_intended_not_container", validate_wave(damaged)["reasons"])

    def test_04_report_preserves_next_steps_container_and_leaf_evidence(self):
        self.assertEqual(self.report["next_steps_intended"], self.source["containers"]["next_steps_intended"])
        self.assertEqual(self.report["leaf_parts"][0]["record_id"], "B")
        self.assertEqual(self.report["generated_by"], "AIRA-of-TERA")

    def test_05_second_wave_is_fira_associated_and_derived_from_report(self):
        self.assertEqual(self.second_wave["association"], "second_fira")
        self.assertEqual(self.second_wave["report"], self.report)

    def test_06_unresolved_status_cannot_silently_become_confirmed(self):
        changed = deepcopy(self.source)
        changed["containers"]["TERA"]["relationships"][0]["status"] = "confirmed"
        result = assertions_aira(self.source, changed)
        self.assertEqual(result["status"], "FAIL")

    def test_07_planned_changes_are_separate_from_actual_changes(self):
        intended = self.report["next_steps_intended"]["intended_changes"]
        self.assertEqual(intended[0]["status"], "planned")
        self.assertEqual(self.report["next_steps_intended"]["status"], "planned")
        self.assertEqual(self.particle["tera_state"]["records"], self.source["containers"]["TERA"]["records"])

    def test_08_duplicate_relationship_is_detected(self):
        damaged = deepcopy(self.source)
        rels = damaged["containers"]["TERA"]["relationships"]
        rels.append(deepcopy(rels[0]))
        self.assertIn("duplicate_relationship", validate_wave(damaged)["reasons"])

    def test_09_post_connection_report_generated_for_success_and_failure(self):
        for outcome in ("SUCCESS", "PARTIAL", "BLOCKED", "FAILED", "UNKNOWN"):
            report = generate_post_connection_report({"outcome": outcome})
            self.assertTrue(report["generated"])
            self.assertEqual(report["outcome"], outcome)
            self.assertEqual(report["persistence_status"], "NOT_VERIFIED")

    def test_10_missing_source_identity_does_not_claim_verification(self):
        report = generate_post_connection_report({"outcome": "SUCCESS"})
        self.assertEqual(report["source_id"], "UNKNOWN")
        self.assertEqual(report["source_version"], "UNKNOWN")
        self.assertEqual(report["persistence_status"], "NOT_VERIFIED")
        self.assertIn("connection_runtime_unverified", report["unverified_boundaries"])


if __name__ == "__main__":
    unittest.main()
